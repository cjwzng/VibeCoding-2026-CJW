// common.js : 모든 페이지 공통 기능 (햄버거 메뉴)
// - main.js 보다 먼저 불러온다
// - 상단영역(.top-area)에 필요한 요소가 없는 페이지에서는 실행하지 않는다
// =====================================================

// 자바스크립트 월드에 오신것을 환영합니다!
console.log('안뇽!');

// document는 전체 문서객체(DOM-Document Object Model)
// 점(.)은 객체의 하위 속성으로 들어감
// 요소 선택법 : querySelector(CSS선택자)
// -> 첫번째 만난 요소 하나만 가져옴
// -> 참고로 여러요소선택은 querySelectorAll(CSS선택자)

//////// 햄버거 버튼 클릭시 메뉴 보이기/숨기기 ////////
// 1. 대상선정
// 1-1. 이벤트 대상: 햄버거버튼(.menu-btn)
// 변수는 따옴표로 싸지 않는 문자다. 변수는 let으로 선언한다.
let 햄버거 = document.querySelector('.menu-btn');

// 1-2. 변경대상: 상단영역(.top-area)
let 상단박스 = document.querySelector('.top-area');

// 요소가 없으면 null 이므로, 둘 다 있을 때만 이벤트를 설정한다!
if (햄버거 && 상단박스) {
  // 2. 이벤트 함수 만들기
  // 햄버거 클릭시 상단박스 클래스 on 넣기
  햄버거.onclick = () => {
    상단박스.classList.toggle('on');
    // classList 객체는 클래스를 넣고 빼는 기능을 가짐
    // add(클래스명) - 클래스넣기
    // remove(클래스명) - 클래스빼기
    // toggle(클래스명) - 클래스넣기/빼기 전환
  }; //////////클릭함수//////////

  console.log('선택확인:', 햄버거, 상단박스);
}
