// 최종 요구사항
// -> 상단 배너 클릭시
// 상단 메뉴 배경색을 변경하고
// 상단 메뉴는 360도 회전함
// 트랜지션으로 애니메이션 2초간 되게함

// 대상선정:
// 1. 이벤트 대상 : 상단배너 (.main-visual-img)
let 너를클릭해 = document.querySelector('.main-visual-img');
// 2. 변경대상 : 상단영역
// (common.js의 변수와 이름이 겹치면 오류가 나므로 여기서 다시 선택함)
let 나야나 = document.querySelector('.top-area');

console.log('나는 누구인가?', 나야나);

// 페이지 전용 요소가 있을 때만 기능을 설정한다!
if (너를클릭해 && 나야나) {
  // 아래의 코드가 바로 실행하지 않고
  // 호출시에만 실행하도록 하려면? 함수안에 넣어준다!
  // 함수 이름을 호출할때 실행됨!

  // 원래 함수
  // function 함수명(전달변수){코드}
  // 화살표 함수가 유행~~!
  // let 함수담을변수 = (전달변수)=>{코드}

  // const 는 상수 또는 함수를 담는 변수선언
  // 보안상 let보다 const를 함수담을때 많이 씀.

  // const 나야나함수 = ()=>{};
  const 나야나함수 = (색상) => {
    console.log('함수호출! 전달값은?', 색상);
    // 상단요소의 배경색 바꾸기
    나야나.style.backgroundColor = 색상;
    나야나.style.transition = '2s ease-in-out';
    // 회전은 로고가 하도록 변경
    나야나.querySelector('.logo-box').style.rotate = '360deg';
    // 로고 트랜지션 : 2초후 1초간 ease-in-out
    나야나.querySelector('.logo-box').style.transition = '1s ease-in-out 2s';
  }; ///////// 나야나함수 /////////

  // 할당된 화살표함수는 반드시 함수 아래쪽에서 호출해야함!
  // 또는 이벤트 발생시엔 상관없음.

  // 함수는 호출시 함수명(전달값) -> 소괄호 필수
  // 만약 전달변수가 있다면 값을 써서 보내야함!

  // 3. 이벤트 설정하기 : 클릭이벤트
  // 클릭이벤트는 onclick 속성으로 셋팅!
  // 클릭시 함수호출은 바로실행 안되게 화살표함수로 표시
  너를클릭해.onclick = () => {
    // 해당요소에 클릭이벤트가 발생하면 이 구역을 실행함
    나야나함수('orange');
  }; ///// onclik 함수 ///////
}


// =====================================================
// place 영역 : 배경 이미지 슬라이드 (바닐라 JS)
// - 처음엔 1번 이미지가 보임
// - 2초 대기 -> 1초 동안 오른쪽에서 왼쪽으로 이동 -> 반복
// - 3번 다음에 1번이 "다시 오른쪽에서" 들어오도록
//   첫번째 박스를 복제해서 맨 뒤에 붙여둠 (무한반복용)
// =====================================================
// (()=>{코드})() -> 변수명 중복 위험을 없애준다!
// 이 구역은 바로 실행됨! 중괄호안이 지역변수가 됨!
// 전역변수는 함수바깥에 있는 변수
// 지역변수는 함수 내부에 있는 변수
// 아래처럼 쓰고 중괄호안에 코드를 넣으면 된다
/* 
    (() =>{
       내코드....
       
    })();
 */
(() => {
  const 트랙 = document.querySelector('.place-track');
  // place 슬라이더가 없는 페이지에서는 실행하지 않는다
  if (!트랙) return;

  const 대기시간 = 2000; // 2초 대기
  const 이동시간 = 1000; // 1초 이동

  // 원본 박스 개수(3개)를 먼저 센 다음, 첫번째 박스 복제본을 맨 뒤에 추가
  const 원본개수 = 트랙.children.length;
  const 복제본 = 트랙.children[0].cloneNode(true);
  트랙.appendChild(복제본);

  let 순번 = 0;

  // 한 칸 이동 함수
  const 다음으로 = () => {
    순번++;
    트랙.style.transition = `transform ${이동시간}ms ease-in-out`;
    트랙.style.transform = `translateX(-${순번 * 100}%)`;
  }; ///////// 다음으로 함수 /////////

  // 이동이 끝나면 호출됨
  트랙.addEventListener('transitionend', (e) => {
    if (e.target !== 트랙) return;

    // 복제본(맨 뒤 1번 이미지)에 도착했으면
    // 트랜지션 없이 진짜 1번 위치로 순간이동 (눈에는 안 보임)
    if (순번 === 원본개수) {
      트랙.style.transition = 'none';
      트랙.style.transform = 'translateX(0)';
      순번 = 0;
      void 트랙.offsetWidth; // 리플로우 강제 : 위 설정을 바로 적용시킴
    }

    // 2초 쉬고 다시 이동
    setTimeout(다음으로, 대기시간);
  }); ///////// transitionend /////////

  // 최초 시작 : 1번 이미지를 2초 보여준 후 이동 시작
  setTimeout(다음으로, 대기시간);
})();